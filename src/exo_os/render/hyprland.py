"""Render the machine profile into Hyprland (0.56 Lua API) and hypridle config.

Output paths are relative to the person's config folder (~/.config). The image ships a fixed
~/.config/hypr/hyprland.lua that loads `hypr/exo/profile.lua`, so the only Hyprland file Exo OS writes
is generated, and a person's own edits elsewhere are never overwritten.
"""
from __future__ import annotations

from ..profile import Profile

HEADER = "-- Generated by Exo OS from the machine profile. Do not edit: ask Exo, or run `exo-os set`.\n"
APP_CMD = "exo-os app open"
SURFACE_CMD = "exo-surface toggle"


def render(profile: Profile) -> dict[str, str]:
    return {"hypr/exo/profile.lua": profile_lua(profile), "hypr/hypridle.conf": hypridle(profile)}


def lua_str(s: str) -> str:
    return '"' + s.replace("\\", "\\\\").replace('"', '\\"').replace("\n", "\\n") + '"'


def lua_key(key: str) -> str:
    return " + ".join(key.split("+"))


def class_pattern(cls: str) -> str:
    """An anchored Hyprland regex that matches exactly this window class."""
    out = "".join("\\" + c if c in ".^$*+?()[]{}|\\" else c for c in cls)
    return f"^{out}$"


def _num(v: float | int) -> str:
    return repr(v) if isinstance(v, int) else f"{v:g}"


def profile_lua(profile: Profile) -> str:
    d = profile.data
    disp, kb, ptr, look, surf = d["display"], d["keyboard"], d["pointer"], d["look"], d["surface"]
    lines = [HEADER]

    lines += ["-- Display",
              f'hl.monitor({{ output = "", mode = "preferred", position = "auto", scale = {_num(disp["scale"])} }})',
              f'hl.env("GDK_DPI_SCALE", {lua_str(_num(disp["text_scale"]))})',
              f'hl.env("QT_SCALE_FACTOR", {lua_str(_num(disp["text_scale"]))})',
              ""]

    lines += ["-- Keyboard, pointer, look",
              "hl.config({",
              "  input = {",
              f'    kb_layout = {lua_str(",".join(kb["layouts"]))},',
              f'    kb_options = {lua_str(kb["switch"])},',
              f'    repeat_rate = {kb["repeat_rate"]},',
              f'    repeat_delay = {kb["repeat_delay"]},',
              f'    sensitivity = {_num(ptr["sensitivity"])},',
              f'    touchpad = {{ natural_scroll = {str(ptr["natural_scroll"]).lower()} }},',
              "  },",
              "  general = {",
              f'    gaps_in = {look["gaps"] // 2},',
              f'    gaps_out = {look["gaps"]},',
              f'    border_size = {look["border"]},',
              "  },",
              "})",
              ""]

    lines += ["-- The prompt bar",
              f'hl.bind({lua_str(lua_key(surf["key"]))}, hl.dsp.exec_cmd({lua_str(SURFACE_CMD)}), '
              '{ description = "Ask Exo" })',
              ""]

    lines.append("-- Apps: one key and one workspace each, always full size")
    starts = []
    for app in d["apps"]:
        name = app["name"]
        open_cmd = f"{APP_CMD} {_shell_word(name)}"
        if app.get("key"):
            lines.append(f'hl.bind({lua_str(lua_key(app["key"]))}, hl.dsp.exec_cmd({lua_str(open_cmd)}), '
                         f'{{ description = {lua_str(name)} }})')
        if app.get("class") and app.get("workspace"):
            rule = [f"match = {{ class = {lua_str(class_pattern(app['class']))} }}"]
            if app.get("workspace"):
                rule.append(f'workspace = "{app["workspace"]} silent"' if app.get("autostart")
                            else f'workspace = "{app["workspace"]}"')
                rule.append("maximize = true")
            lines.append(f"hl.window_rule({{ {', '.join(rule)} }})")
        if app.get("autostart"):
            starts.append(open_cmd + " --background")
    lines.append("")

    if starts:
        lines += ["-- Opened at login", 'hl.on("hyprland.start", function()']
        lines += [f"  hl.exec_cmd({lua_str(cmd)})" for cmd in starts]
        lines += ["end)", ""]
    return "\n".join(lines)


def hypridle(profile: Profile) -> str:
    idle = profile.data["idle"]
    out = ["# Generated by Exo OS from the machine profile. Do not edit.",
           "general {",
           "    lock_cmd = pidof hyprlock || hyprlock",
           "    before_sleep_cmd = loginctl lock-session",
           "    after_sleep_cmd = hyprctl dispatch dpms on",
           "}", ""]
    if idle["dim_seconds"]:
        out += ["listener {", f"    timeout = {idle['dim_seconds']}",
                "    on-timeout = brightnessctl -s set 30%", "    on-resume = brightnessctl -r", "}", ""]
    if idle["lock_seconds"]:
        out += ["listener {", f"    timeout = {idle['lock_seconds']}", "    on-timeout = loginctl lock-session",
                "}", ""]
    if idle["screen_off_seconds"]:
        out += ["listener {", f"    timeout = {idle['screen_off_seconds']}",
                "    on-timeout = hyprctl dispatch dpms off", "    on-resume = hyprctl dispatch dpms on", "}", ""]
    return "\n".join(out)


def _shell_word(s: str) -> str:
    return "'" + s.replace("'", "'\\''") + "'"
